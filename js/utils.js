function icon(name, size = 18) {
  const svg = ICONS[name];
  if (!svg) return '';
  return svg.replace('<svg', `<svg width="${size}" height="${size}"`);
}

// ── TOAST ─────────────────────────────────────────────────────────────────
function toast(msg, type = 'info') {
  const container = document.getElementById('toast-container');
  if (!container) return;
  const el = document.createElement('div');
  el.className = `toast ${type}`;
  const iconMap = { success: 'check', error: 'close', info: 'info' };
  const colors = { success: '#34d399', error: '#f87171', info: '#60a5fa' };
  el.innerHTML = `<span style="color:${colors[type]}">${icon(iconMap[type] || 'info', 18)}</span><span class="toast-msg">${msg}</span>`;
  container.appendChild(el);
  setTimeout(() => { el.style.opacity = '0'; el.style.transition = 'opacity 0.3s'; setTimeout(() => el.remove(), 300); }, 3000);
}

// ── MODAL HELPERS ─────────────────────────────────────────────────────────
function openModal(id) {
  const m = document.getElementById(id);
  if (m) { m.classList.add('open'); document.body.style.overflow = 'hidden'; }
}

function closeModal(id) {
  const m = document.getElementById(id);
  if (m) { m.classList.remove('open'); document.body.style.overflow = ''; }
}

// Close modal on overlay click
document.addEventListener('click', e => {
  if (e.target.classList.contains('modal-overlay')) {
    e.target.classList.remove('open');
    document.body.style.overflow = '';
  }
});

// ── CONFIRM DELETE ────────────────────────────────────────────────────────
function confirmDelete(name, callback) {
  const overlay = document.getElementById('confirm-modal');
  document.getElementById('confirm-msg').textContent = `Delete "${name}"? This cannot be undone.`;
  overlay.classList.add('open');
  document.getElementById('confirm-yes').onclick = () => {
    overlay.classList.remove('open');
    callback();
  };
  document.getElementById('confirm-no').onclick = () => overlay.classList.remove('open');
}

// ── SEARCH / FILTER ───────────────────────────────────────────────────────
function filterRows(rows, query, keys) {
  if (!query) return rows;
  const q = query.toLowerCase();
  return rows.filter(r => keys.some(k => String(r[k] || '').toLowerCase().includes(q)));
}

// ── EXPORT CSV ────────────────────────────────────────────────────────────
function exportCSV(headers, rows, filename) {
  const lines = [headers.join(','), ...rows.map(r => headers.map(h => `"${r[h] ?? ''}"`).join(','))];
  const blob = new Blob([lines.join('\n')], { type: 'text/csv' });
  const a = document.createElement('a');
  a.href = URL.createObjectURL(blob);
  a.download = filename;
  a.click();
  URL.revokeObjectURL(a.href);
}

